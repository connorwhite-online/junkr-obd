#!/usr/bin/env python3
"""Write src/ecu/board_pins.h from circuit.py, so firmware and board share one pin map.

    /usr/bin/python3 gen_pins.py
"""
import os

import circuit as CIR

HERE = os.path.dirname(os.path.abspath(__file__))
DST = os.path.join(HERE, "..", "..", "..", "src", "ecu", "board_pins.h")


def main():
    lines = ["// Generated by kicad/standalone_ecu/tools/gen_pins.py from circuit.py. Do not edit.",
             "// STM32H743ZIT6 (U100) pin map for the JUNKR standalone ECU rev A.",
             "#pragma once", "#include <stdint.h>", "", "namespace board {", "",
             "struct Pin { char port; uint8_t num; const char *af; };", ""]
    for pin, net in sorted(CIR.MCU_PINS.items(), key=lambda kv: (kv[0][1], int(kv[0][2:]))):
        af = CIR.MCU_AF.get(pin)
        if af is None and pin in CIR.ADC_PINS:
            af = "ADC"
        lines.append('constexpr Pin %-12s = {\'%s\', %2d, %s};' % (net, pin[1], int(pin[2:]),
                                                                  '"%s"' % af if af else "nullptr"))
    lines += ["", "}  // namespace board", ""]
    with open(DST, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(DST), len(CIR.MCU_PINS), "pins")


if __name__ == "__main__":
    main()
