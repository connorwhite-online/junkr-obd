#!/usr/bin/env python3
"""Dump the routed board into OpenSCAD arrays for the renders and the cover.

    python3 export_scene.py   -> ../../hardware/ecu_interposer/cad/pcb_board_data.scad

Coordinates: X = footprint x, Y = -footprint y (so the harness edge is +Y),
Z up from the board's bottom face.
"""
import os

import pcbnew as P

import gen_board as G

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "hardware", "ecu_interposer", "cad", "pcb_board_data.scad")


def xy(v):
    return round(P.ToMM(v.x) - G.OX, 3), round(-(P.ToMM(v.y) - G.OY), 3)


b = P.LoadBoard(os.path.join(HERE, "interposer.kicad_pcb"))
holes, smd, tracks = [], [], []
for pad in b.GetPads():
    x, y = xy(pad.GetPosition())
    sx, sy = round(P.ToMM(pad.GetSize().x), 3), round(P.ToMM(pad.GetSize().y), 3)
    if pad.GetAttribute() in (P.PAD_ATTRIB_PTH, P.PAD_ATTRIB_NPTH):
        plated = 1 if pad.GetAttribute() == P.PAD_ATTRIB_PTH else 0
        holes.append([x, y, round(P.ToMM(pad.GetDrillSize().x), 3), sx if plated else 0, plated])
    else:
        smd.append([x, y, sx, sy, 0 if pad.IsOnLayer(P.F_Cu) else 1])
for t in b.GetTracks():
    if t.GetClass() == "PCB_VIA":
        x, y = xy(t.GetPosition())
        holes.append([x, y, 0.3, 0.6, 1])
        continue
    a, c = xy(t.GetStart()), xy(t.GetEnd())
    tracks.append([a[0], a[1], c[0], c[1], round(P.ToMM(t.GetWidth()), 3), 0 if t.GetLayer() == P.F_Cu else 1])
x0, y0, x1, y1 = G.BOARD
with open(OUT, "w") as f:
    f.write("// generated by kicad/interposer/export_scene.py, do not edit\n")
    f.write(f"PCB_OUTLINE = [{x0}, {-y1}, {x1}, {-y0}];   // x0, y0, x1, y1 (3D frame)\n")
    f.write(f"PCB_CUT = [{G.CUT[0]}, {-G.CUT[3]}, {G.CUT[2]}, {-G.CUT[1]}];   // notch, not board (3D frame)\n")
    f.write(f"PCB_T = 1.6;\n")
    f.write(f"PCB_MOUNT = {[[x, -y] for x, y in G.MOUNT]};\n")
    f.write(f"PCB_HOLES = {holes};   // x, y, drill, pad, plated\n")
    f.write(f"PCB_SMD = {smd};       // x, y, w, h, side (1 = bottom)\n")
    f.write(f"PCB_TRACKS = {tracks}; // x0, y0, x1, y1, w, side\n")
    tails = []
    for plug, d in G.PLUGS.items():
        n = len(d["cols"])
        for i, (x, t) in enumerate(d["cols"]):
            xr, _ = G.route_x(plug, i)
            tails.append([x, -G.TAIL_Y[0], x, t, 0])
            tails.append([xr, -G.TAIL_Y[1], x, t, 1])
    f.write(f"PCB_TAILS = {tails};   // hole x, hole y, pin column x, type, row\n")
print("wrote", os.path.relpath(OUT))
